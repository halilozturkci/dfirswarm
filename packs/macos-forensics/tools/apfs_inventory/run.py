class Capture:
    """What a program printed: written to two files as it comes (when `keep`), counted, and the head of stdout kept in memory for the parse."""

    def __init__(self, keep, head_limit):
        self.head = bytearray()
        self.head_limit = head_limit
        self.err_head = bytearray()
        self.total = 0
        self.counts = {"stdout": 0, "stderr": 0}
        self.files = {}
        self.keep = keep
        if keep:
            directory, _shown = output_dir()
            directory.mkdir(parents=True, exist_ok=True)
            for which in ("stdout", "stderr"):
                name = str(directory / (".apfs-%d-%s-%s" % (os.getpid(), which, os.urandom(4).hex())))
                TEMPS.append(name)                      # registered before the file exists: a stop between the two leaves nothing unnamed
                try:
                    fd = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
                except OSError as exc:
                    raise StorageRefused("%s: %s" % (type(exc).__name__, exc.strerror or "error"))
                self.files[which] = (name, fd)

    def write(self, which, data):
        self.counts[which] += len(data)
        self.total += len(data)
        if which == "stdout":
            if len(self.head) < self.head_limit:
                self.head += data[:self.head_limit - len(self.head)]
        elif len(self.err_head) < 8192:
            self.err_head += data[:8192 - len(self.err_head)]
        if self.keep:
            fd = self.files[which][1]
            view = memoryview(data)
            try:
                while view:
                    view = view[os.write(fd, view):]
            except OSError as exc:
                raise StorageRefused("%s: %s" % (type(exc).__name__, exc.strerror or "error"))

    def close(self):
        for _name, fd in self.files.values():
            try:
                os.fsync(fd)
            except OSError:
                pass
            try:
                os.close(fd)
            except OSError:
                pass
        self.files = {k: (v[0], -1) for k, v in self.files.items()}


def run_program(argv, seconds, cap, keep):
    """Run a program in this tool's process group and read its output as it comes. Returns a dict: exit code, whether the deadline or the cap ended it,
    whether pipes were held by something it started, and the Capture."""
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LC_ALL": "C", "LANG": "C"}
    result = {"started": False, "exit_code": None, "timed_out": False, "capped": False, "pipes_held": False}
    capture = Capture(keep, PARSE_BYTES if keep else 65536)
    result["capture"] = capture
    try:
        proc = spawn(argv, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env)
    except OSError as exc:
        result["why"] = "%s: %s" % (type(exc).__name__, exc.strerror or "error")
        return result
    result["started"] = True
    ACTIVE.append(proc)
    selector = selectors.DefaultSelector()
    try:
        for name, pipe in (("stdout", proc.stdout), ("stderr", proc.stderr)):
            os.set_blocking(pipe.fileno(), False)
            selector.register(pipe, selectors.EVENT_READ, name)
        deadline = time.monotonic() + max(0.1, seconds)
        ended_at = None
        while selector.get_map():
            check_stop()
            now = time.monotonic()
            if now >= deadline:
                result["timed_out"] = True
                kill_tree(proc)
                break
            if capture.total > cap:
                result["capped"] = True
                kill_tree(proc)
                break
            if proc.poll() is None:
                _sample(proc.pid)                      # the tree below the program is noted, so that a child that outlives it can be found and ended
            for key, _events in selector.select(timeout=0.2):
                try:
                    data = os.read(key.fd, 65536)
                except BlockingIOError:
                    continue
                if not data:
                    selector.unregister(key.fileobj)
                    continue
                capture.write(key.data, data)
            if proc.poll() is not None:
                if ended_at is None:
                    ended_at = time.monotonic()
                elif time.monotonic() - ended_at > PIPE_GRACE:
                    # the program is gone and something it started holds its pipes: the pipes are let go, and what holds them (and is ours) is ended
                    result["pipes_held"] = True
                    reap_orphans(_pipe_inodes(proc))
                    break
        try:
            result["exit_code"] = proc.wait(timeout=max(0.1, min(5.0, deadline - time.monotonic()) if not (result["timed_out"] or result["capped"]) else 5.0))
        except subprocess.TimeoutExpired:
            result["timed_out"] = True
            kill_tree(proc)
            result["exit_code"] = proc.wait()
    except Interrupted:
        result["stopped"] = True                       # the hook of the stop block already ended the tree; the capture so far is kept, and the caller raises the stop again
    finally:
        if proc.poll() is None:
            kill_tree(proc)
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                pass
        if proc in ACTIVE:
            ACTIVE.remove(proc)
        selector.close()
        for pipe in (proc.stdout, proc.stderr):
            try:
                if pipe is not None:
                    pipe.close()
            except (OSError, ValueError):
                pass
    return result


def keep_file(temp_name, stem, which, key):
    """Make a temporary output file into its result, named by a digest of the request: a rerun that would replace a larger earlier file writes a new name.
    Returns (name as the answer shows it, the earlier larger file it kept or None)."""
    directory, shown = output_dir()
    digest = hashlib.sha256(json.dumps(key, sort_keys=True, default=str).encode("utf-8")).hexdigest()[:16]
    target = directory / ("%s-%s.%s.txt" % (stem, digest, which))
    kept = None
    if target.exists() and target.stat().st_size > os.path.getsize(temp_name):
        kept = "%s/%s" % (shown, target.name)
        n = 2
        while target.with_name("%s-%s-%d.%s.txt" % (stem, digest, n, which)).exists():
            n += 1
        target = target.with_name("%s-%s-%d.%s.txt" % (stem, digest, n, which))
    os.replace(temp_name, target)
    if temp_name in TEMPS:
        TEMPS.remove(temp_name)
    return "%s/%s" % (shown, target.name), kept


def parse_sections(text):
    """The sections of fsapfsinfo's output: {"container": [...], "volumes": [...], "other": n}, each section a dict of its heading and its label/value lines."""
    sections, current = [], None
    lines = parsed = unparsed = long_lines = 0
    for raw in text.split("\n"):
        if lines >= LINES_MAX:
            break
        lines += 1
        line = raw.rstrip("\r")
        if not line.strip():
            continue
        if len(line) > LINE_MAX:
            long_lines += 1
            unparsed += 1
            continue
        if BANNER.match(line.strip()):
            parsed += 1                                  # the program's own first line (name and version)
            continue
        heading = HEADING.match(line.strip())
        if heading and not line.startswith((" ", "\t")):
            if len(sections) < SECTIONS_MAX:
                current = {"kind": heading.group(1).lower(), "heading": line.strip(), "fields": {}, "dupes": 0, "unlisted": 0}
                sections.append(current)
            else:
                current = None
                unparsed += 1
            parsed += 1
            continue
        label, colon, value = line.partition(":")
        label = label.strip()
        if not colon or not label or len(label) > 80:
            unparsed += 1
            continue
        if current is None:
            if len(sections) < SECTIONS_MAX:
                current = {"kind": "preamble", "heading": None, "fields": {}, "dupes": 0, "unlisted": 0}
                sections.append(current)
            else:
                unparsed += 1
                continue
        parsed += 1
        key = label.lower()
        if key in current["fields"]:
            current["dupes"] += 1
        elif len(current["fields"]) < FIELDS_PER_SECTION:
            current["fields"][key] = value.strip()
        else:
            current["unlisted"] += 1
    return sections, {"lines_total": lines, "lines_parsed": parsed, "unparsed_lines": unparsed, "long_lines": long_lines, "cut": lines >= LINES_MAX}


def shape_section(section):
    fields = section["fields"]
    out = {"heading": section["heading"], "fields": fields}
    for label in IDENTIFIER_LABELS:
        if label in fields:
            out["identifier"] = fields[label]
            break
    for label in NAME_LABELS:
        if label in fields:
            out["name"] = fields[label]
            break
    counts = {k: int(v) for k, v in fields.items() if k.startswith("number of") and re.fullmatch(r"[0-9]{1,15}", v)}
    if counts:
        out["counts"] = counts
    enc = {k: v for k, v in fields.items() if ENCRYPTION_WORDS.search(k)}
    if enc:
        out["encryption"] = enc
    if section["unlisted"]:
        out["fields_not_listed"] = section["unlisted"]
    if section["dupes"]:
        out["duplicate_labels"] = section["dupes"]
    return out


def run_apfs(args):
    started = time.monotonic()
    path = args.get("path")
    if not isinstance(path, str) or not path:
        fail("path is required: an APFS container image (a regular file)")
    offset = args.get("offset", 0)
    if not isinstance(offset, int) or isinstance(offset, bool) or offset < 0:
        fail("offset must be a non-negative integer (bytes)", offset=offset if isinstance(offset, (int, float, str, type(None))) and len(str(offset)) < 40 else None)
    max_seconds = args.get("max_seconds", DEFAULT_MAX_SECONDS)
    if not isinstance(max_seconds, (int, float)) or isinstance(max_seconds, bool) or max_seconds <= 0:
        fail("max_seconds must be a positive number", max_seconds=max_seconds)
    requested = max_seconds
    max_seconds = min(max_seconds, MAX_SECONDS_LIMIT)
    max_output = args.get("max_output_bytes", DEFAULT_MAX_OUTPUT)
    if not isinstance(max_output, int) or isinstance(max_output, bool) or max_output < 1:
        fail("max_output_bytes must be a positive integer", max_output_bytes=max_output if isinstance(max_output, (int, float, str, type(None))) and len(str(max_output)) < 40 else None)
    OWN_NAMES.add(path)
    try:
        info = os.lstat(path)
    except OSError as exc:
        fail("no such file", path=path, reason=exc.strerror or type(exc).__name__)
    if stat.S_ISLNK(info.st_mode):
        fail("path is a symbolic link: name the file it resolves to (evidence is not followed through a link)", path=path)
    if not stat.S_ISREG(info.st_mode):
        fail("path is not a regular file: read an image made from the device or the directory", path=path)
    if offset >= info.st_size:
        fail("offset is at or past the end of the file", path=path, offset=offset)
    found = shutil.which(PROGRAM)
    SWEEP["began"] = True
    st = {"interrupted": None, "version": None, "run": None, "storage": None}
    notes = []

    def work():
        if found is None:
            return
        version = run_program([found, "-V"], VERSION_SECONDS, 65536, False)
        st["version"] = version
        check_stop()
        if not version["started"] or version["exit_code"] != 0 or version["timed_out"]:
            return
        target = path if not path.startswith("-") else "./" + path
        argv = [found] + (["-o", str(offset)] if offset else []) + [target]
        st["run"] = run_program(argv, max_seconds, max_output, True)
        check_stop()

    try:
        try:
            work()
            hold_signals()
        except Interrupted as stop:
            st["interrupted"] = stop.signum
            hold_signals()
        except StorageRefused as exc:
            st["storage"] = str(exc)
            hold_signals()
    finally:
        hold_signals()
    interrupted = st["interrupted"]
    version, run = st["version"], st["run"]
    problems = []
    result = {"path": path, "parser": PARSER, "offset": offset, "program": PROGRAM}
    if interrupted is not None:
        problems.append("the tool was stopped by %s: the program and what it started were ended, and the inventory below is what was read before that" % signal_name(interrupted))
    if st["storage"]:
        remove_temporaries()
        problems.append("a write to the output directory was refused (%s): this says nothing about the container; the output files were not made" % st["storage"])
    if found is None:
        result.update(status="failed", status_basis="fsapfsinfo is not installed here (not on PATH): nothing was read and nothing is claimed about the container", reader={"found": None})
        problems.append("the reader fsapfsinfo (libfsapfs-utils) is not on PATH; the base pack lists it as optional, and it is not in every image")
    else:
        reader = {"found": found}
        if version is not None:
            reader["version_exit"] = version["exit_code"]
            text = bytes(version["capture"].head).decode("utf-8", "backslashreplace") if version["started"] else ""
            first = next((ln.strip() for ln in text.splitlines() if ln.strip()), None)
            if first is None:
                first = next((ln.strip() for ln in bytes(version["capture"].err_head).decode("utf-8", "backslashreplace").splitlines() if ln.strip()), None)
            reader["version_line"] = first[:200] if first else None
            if not version["started"]:
                problems.append("fsapfsinfo -V could not be started (%s)" % version.get("why", "error"))
            elif version["exit_code"] != 0 or version["timed_out"]:
                problems.append("fsapfsinfo -V %s: the version of the reader is not recorded" % ("did not end in %s seconds" % VERSION_SECONDS if version["timed_out"] else "exited %s" % version["exit_code"]))
        result["reader"] = reader
        if run is None:
            result.update(status="failed", status_basis="fsapfsinfo could not be run (see problems): nothing was read and nothing is claimed about the container")
        else:
            cap = run["capture"]
            cap.close()
            names = {}
            kept_earlier = {}
            if cap.keep and not st["storage"]:
                key = [path, offset]
                for which in ("stdout", "stderr"):
                    temp = cap.files[which][0]
                    names[which], older = keep_file(temp, "apfs_inventory", which, key)
                    OWN_NAMES.add(names[which])
                    if older:
                        kept_earlier[which] = older
                        OWN_NAMES.add(older)
            sections, counts = parse_sections(bytes(cap.head).decode("utf-8", "backslashreplace"))
            containers = [s for s in sections if s["kind"] == "container"]
            vols = [s for s in sections if s["kind"] == "volume"]
            declared = None
            for s in containers:
                for label, value in s["fields"].items():
                    if label.startswith("number of volumes") and re.fullmatch(r"[0-9]{1,9}", value):
                        declared = int(value)
            result["argv"] = [PROGRAM] + (["-o", str(offset)] if offset else []) + ["<path>"]
            result["exit_code"] = run["exit_code"]
            result["timed_out"] = run["timed_out"]
            result["stdout_bytes"], result["stderr_bytes"] = cap.counts["stdout"], cap.counts["stderr"]
            if names:
                result["stdout_file"], result["stderr_file"] = names["stdout"], names["stderr"]
            for which, older in kept_earlier.items():
                result["kept_earlier_larger_" + which] = older
            err_line = next((ln.strip() for ln in bytes(cap.err_head).decode("utf-8", "backslashreplace").splitlines() if ln.strip()), None)
            if err_line and run["exit_code"] != 0:
                result["stderr_first_line"] = err_line[:300]
            result["container"] = [shape_section(s) for s in containers[:1]]
            result["sections"] = {"section_count": len(sections), "other_sections": sum(1 for s in sections if s["kind"] not in ("container", "volume"))}
            result["volumes_total"] = len(vols)
            result["volumes"] = [shape_section(s) for s in vols[:VOLUMES_LISTED_MAX]]
            if len(vols) > VOLUMES_LISTED_MAX:
                result["volumes_listed"] = VOLUMES_LISTED_MAX
                problems.append("%d volume section(s) are not listed (the first %d are); all of them are in stdout_file" % (len(vols) - VOLUMES_LISTED_MAX, VOLUMES_LISTED_MAX))
            result["declared_volumes"] = declared
            result.update({k: v for k, v in counts.items() if k != "cut"})
            if run["timed_out"]:
                problems.append("fsapfsinfo did not end in %s seconds and was ended with what it started" % max_seconds)
            if run["capped"]:
                problems.append("fsapfsinfo wrote more than max_output_bytes (%d) and was ended; everything it wrote before that is in stdout_file and stderr_file" % max_output)
                result["output_capped"] = True
            if run["pipes_held"]:
                problems.append("something fsapfsinfo started held its pipes after it ended; the pipes were let go and what held them (and was ours) was ended")
            verdict = process_verdict()
            for reason in verdict["unproven"]:
                problems.append(reason + ": the files this tool kept (stdout_file, stderr_file) cannot be shown to be final")
            if verdict["left_behind"] and not (run["timed_out"] or run["capped"]):
                problems.append("fsapfsinfo left %d process(es) running after it ended (in the tool's process group or, after setsid or setpgid, outside it); settle() killed and reaped them before the "
                                "files were kept, hashed or counted, so what they would still have written is missing, and stdout_file and stderr_file are what they held at that moment" % verdict["left_behind"])
            if cap.counts["stdout"] > PARSE_BYTES:
                result["parse_cut"] = True
                problems.append("stdout is %d bytes; only the first %d were read for sections (all of it is in stdout_file)" % (cap.counts["stdout"], PARSE_BYTES))
            if counts["cut"]:
                problems.append("the output has more than %d lines; the rest were not read for sections" % LINES_MAX)
            if run["exit_code"] != 0 and not run["timed_out"] and not run["capped"]:
                problems.append("fsapfsinfo exited %s: it did not read the container" % run["exit_code"])
            if run["exit_code"] == 0 and not containers:
                problems.append("fsapfsinfo exited 0 but no Container section was found in its output: the output was not recognised, and nothing is claimed about the container")
            if containers and declared is None:
                problems.append("the output does not state a number of volumes: the volume sections found cannot be checked against it")
            if declared is not None and declared != len(vols):
                problems.append("the reader states %d volume(s) and %d volume section(s) were found" % (declared, len(vols)))
            if counts["unparsed_lines"]:
                problems.append("%d line(s) of the output did not parse as `label : value` or a heading; they are in stdout_file" % counts["unparsed_lines"])
            failed = run["exit_code"] != 0 or run["timed_out"] or run["capped"] or not containers
            if failed:
                result["status"] = "partial" if (containers and run["exit_code"] == 0) or (containers and (run["timed_out"] or run["capped"])) else "failed"
                result["status_basis"] = ("fsapfsinfo %s: %s" % (
                    "was ended at its deadline" if run["timed_out"] else "was ended at max_output_bytes" if run["capped"] else "exited %s" % run["exit_code"],
                    "no container section was read" if not containers else "the sections read before that are below"))
            elif problems:
                result["status"] = "partial"
                result["status_basis"] = "%d problem(s) are named under problems; the sections are what the output held" % len(problems)
            else:
                result["status"] = "complete"
                result["status_basis"] = ("fsapfsinfo ran to its end (exit 0) and its output was read as a container section and %d volume section(s), as many as it states; "
                                          "the labels are the reader's own and were not validated against a build; no snapshot, extraction or unlock is provided" % len(vols))
    if interrupted is not None:
        result["interrupted"] = signal_name(interrupted)
        result["status"] = "partial" if result.get("container") else "failed"      # partial only when a container section was read before the stop
        result["status_basis"] = "the tool was stopped by %s; %s" % (signal_name(interrupted), result.get("status_basis", "nothing was read"))
    elif st["storage"] and result.get("status") != "failed":
        result["status"] = "partial"
    if st["storage"]:
        result["status"] = "failed"
        result["status_basis"] = "the output directory refused a write (a fact about that directory, not about the container): no output was kept and nothing is claimed about the container"
    result["status_basis"] = result.get("status_basis") or "see problems"
    OWN_NAMES.add(result["status_basis"])
    pn = process_notes()
    if pn:
        notes.extend(pn)
    result["problems"] = problems
    if notes:
        result["process_notes"] = notes
    result["snapshots"] = NOT_PROVIDED["snapshots"]
    result["extraction"] = NOT_PROVIDED["extraction"]
    result["view"] = NOT_PROVIDED["view"]
    result["unlock"] = {"used": False, "why": "fsapfsinfo reads a password only from its command line, where the trace would record it: this tool passes none, so an encrypted volume is not opened"}
    result["encryption_route"] = ("If a volume is reported encrypted, the encrypted-containers pack's volumes/filevault-apfs leaf, when that pack is loaded, covers the unlock route; "
                                  "nothing here shows that a volume is unlocked or that its content was read.")
    result["limits"] = {"max_seconds": max_seconds, **({"max_seconds_requested": requested} if requested != max_seconds else {}), "max_output_bytes": max_output,
                        "seconds_used": round(time.monotonic() - started, 1)}
    for text in (NOT_PROVIDED["snapshots"]["why"], NOT_PROVIDED["extraction"]["why"], NOT_PROVIDED["view"]["selected"], result["unlock"]["why"], result["encryption_route"]):
        OWN_NAMES.add(text)
    for n in notes:
        OWN_NAMES.add(n)
    for p in problems:
        OWN_NAMES.add(p)
    OWN_NAMES.update((PROGRAM, "-o", "<path>"))
    process_apply(result)             # program_group: what settle() ended and why absence is unproven; a complete answer becomes partial
    for text in [*result["program_group"]["unproven"], *result["program_group"]["notes"]] + ([result["status_basis"]] if isinstance(result.get("status_basis"), str) else []):
        OWN_NAMES.add(text)
    remove_temporaries()
    hold_signals()
    interrupted = emit_answer(result, interrupted, indent=2)
    close_values()
    if interrupted is not None:
        sys.exit(128 + interrupted)
    if result.get("status") == "failed":
        sys.exit(1)


def main():
    seal_stop_after(SEAL_STOP_SECONDS)
    try:
        args = json.load(sys.stdin)
    except ValueError as exc:
        fail("arguments are not valid JSON", reason=str(exc))
    if not isinstance(args, dict):
        fail("the arguments must be a JSON object")
    STOP["hooks"].append(kill_all)       # a stop signal ends the program and what it started first (the shared PROCESS block), then the tool answers
    run_apfs(args)


def _code(stop):
    return stop.code if isinstance(stop.code, int) else (0 if stop.code is None else 1)


def _leave(code):
    """End the call at once, after the answer is out. The interpreter's own teardown resets the signal handlers to their defaults before it frees
    what the call held, and a stop signal that lands there kills the process by its default action (exit null, not 128 + the signal) with a whole
    answer already printed. What the interpreter would have run at its end (the atexit hooks that remove a temporary file) is run here, with the
    handlers still in; a signal before this point is answered by the handlers as before."""
    try:
        sys.stdout.flush()
    except SystemExit as stop:
        code = _code(stop)
    except Exception:  # noqa: BLE001 - a reader that is gone: the exit code is the one the call had
        pass
    try:
        sys.stderr.flush()
    except Exception:  # noqa: BLE001
        pass
    try:
        import atexit as _atexit
        _atexit._run_exitfuncs()
    except Exception:  # noqa: BLE001 - a hook that fails is not a failure of the answer
        pass
    os._exit(code)


if __name__ == "__main__":
    exit_code = 0
    try:
        install_stop_handlers()
        try:
            main()
        except SystemExit:
            raise
        except Interrupted as stop:
            close_values()
            remove_temporaries()
            emit({"error": "the tool was stopped by %s %s" % (signal_name(stop.signum), "after its read had begun and before its answer was made" if SWEEP["began"] else "before its read began"),
                  "status": "failed",
                  "status_basis": ("stopped by %s after the read had begun: nothing of it is in this answer" if SWEEP["began"] else
                                   "stopped by %s before the read began: nothing was read") % signal_name(stop.signum),
                  "interrupted": signal_name(stop.signum)})
            sys.exit(128 + stop.signum)
        except Exception as exc:                 # whatever hostile input does, the answer is JSON (the class only: a message can quote the evidence)
            close_values()
            remove_temporaries()
            emit({"error": "the tool stopped on an unexpected error", "type": type(exc).__name__, "status": "failed",
                  "status_basis": "the tool stopped with an unexpected error: nothing is complete"})
            sys.exit(1)
    except SystemExit as stop:
        exit_code = _code(stop)
    _leave(exit_code)
