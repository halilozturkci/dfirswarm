            result["argv"] = [PROGRAM, "-o", "<run_directory>/out"] + [FORMAT_FLAGS[f] for f in formats] + (["-pf", "<password_file>"] if password_file else []) + (["-d"] if decrypted else []) + [input_type, "<input>"] + plugins
            result["exit_code"], result["timed_out"] = run.exit_code, run.timed_out
