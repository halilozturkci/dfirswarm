#!/usr/bin/env python3
"""Run the pinned mac_apt over an acquisition, in the input mode that matches it, and say per plugin what its log shows.

mac_apt (ydkhatri/mac_apt, pinned at 1.33.2, amd64 worker image only) parses macOS evidence plugin by plugin. This tool starts it and reads its LOG, because
mac_apt exits 0 after many errors it has logged (its own Exit helper calls sys.exit() whatever the message): the exit code is never the status.

WHAT WAS READ AND WHAT WAS NEVER SEEN. mac_apt was not installed or run to build this tool. The argument shape was read from the source of v1.33.2
(mac_apt.py on GitHub's raw view, 2026-11-04): the positional input type (AFF4, AXIOMZIP, DD, DMG, E01, MOUNTED, SPARSE, UAC, VMDK, VR), the positional plugin
list (upper-cased; ALL and FAST are sets; a trailing - excludes a plugin), -o (output folder), -x -c -t -j (output formats), -pf (a file holding the password or
recovery key, so none is ever on a command line), -d (the image is already decrypted), the log file name Log.<%Y%m%d-%H%M%S>.txt in the output folder, and the
texts of the start line, the plugin start and end lines, the plugin exception line and the finish line. NOT read, never observed: the prefix of a log line, the
wording of a plugin that finds nothing or does not take an operating-system version, the per-plugin file names of the output formats, and mac_apt's behaviour on an
encrypted image without a password. The tool's tests drive it with stand-in programs shaped from the lines above, which proves the tool's reading of those shapes
and nothing about a real run.

* The input type must match the acquisition: a folder for MOUNTED, a file for the others, and the signature of E01, SPARSE, VMDK, DMG (the koly trailer), a zip for
  AFF4 and AXIOMZIP, the suffix of UAC and VR; a mismatch is refused before mac_apt starts. A link is refused.
* A FileVault password is only ever a sealed file (password_file, mode 0600) handed to mac_apt as -pf; this tool never reads it. A password argument does not
  exist; any argument this tool does not know is refused.
* mac_apt runs in this tool's process group under the shared PROCESS block (a deadline, SIGTERM, SIGINT or SIGHUP end it and what it started; PR_SET_PDEATHSIG on
  Linux; never a session of its own), with its working directory, TMPDIR and HOME inside a run directory of its own, created for this run only. Its stdout and stderr
  are written whole to files; nothing is cut.
* Per plugin: `parsed` (it started, ran to its end line and has no exception, error line or traceback inside its run), `empty` (as parsed, and every line inside its run
  says nothing was found; the wording is assumed), `unsupported` (a line inside its run says it does not support something, or mac_apt found no macOS installation;
  the wording is assumed) and `failed` (an exception, an error line, a traceback, no end line, started twice, or requested and never started). A plugin is never
  `parsed` from output nothing here recognised. The status is `complete` only when mac_apt exited 0, its log was recognised from the start line to the finish line,
  every requested plugin is parsed or empty, and no error line sits outside a plugin; a run of ALL or FAST can never be complete, because the plugins they expand to are
  not listed by anything read here.
* No log text is kept in the answer: a log line can quote the evidence. The kept log and the output files hold it; the output is a sensitive output (the manifest
  declares secret_output: required).
"""
