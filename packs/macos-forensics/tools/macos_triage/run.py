        if run is None or not run.started:
            result.update(status="failed", status_basis=own("mac_apt.py could not be started: nothing was run and nothing is claimed about the evidence"))
            if run is not None and run.why:
                problems.append("mac_apt.py could not be started (%s)" % run.why.split(":")[0])
